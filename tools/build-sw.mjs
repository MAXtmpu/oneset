// Regenerates sw.js with the full app-shell file list and a content hash as the cache version.
// Run after any change you deploy:  node tools/build-sw.mjs  (the web app lives in app/)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../app/', import.meta.url));
const include = ['index.html', 'styles.css', 'manifest.webmanifest', 'js', 'icons'];

function walk(p) {
  const s = statSync(p);
  if (s.isDirectory()) return readdirSync(p).flatMap((f) => walk(join(p, f)));
  return [p];
}

const files = include.flatMap((f) => walk(join(root, f)))
  .filter((f) => !/\.DS_Store$/.test(f))
  .map((f) => relative(root, f))
  .sort();
const hash = createHash('sha256');
files.forEach((f) => hash.update(f).update(readFileSync(join(root, f))));
const version = hash.digest('hex').slice(0, 10);

const sw = `// GENERATED by tools/build-sw.mjs. Do not edit by hand.
// Cache-first app shell so the app works with no signal in the gym.
const VERSION = '${version}';
const CACHE = 'myodose-app-' + VERSION;
const FILES = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith('myodose-app-') && k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      return await fetch(req);
    } catch {
      return (await caches.match('./index.html')) || Response.error();
    }
  })());
});
`;
writeFileSync(join(root, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, version ${version}`);
